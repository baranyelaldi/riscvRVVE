.text
.global _start
_start:
    # v1 = {0xFF, 0xFF, 0xFF, 0xFF}, v2 = {0x0F, 0x0F, 0x0F, 0x0F}
    li      t0, 0xFF
    vmv.v.x v1, t0
    li      t0, 0x0F
    vmv.v.x v2, t0

    # vand: 0xFF & 0x0F = 0x0F
    vand.vv v3, v1, v2          # v3 = {0x0F, 0x0F, 0x0F, 0x0F}

    # vor: 0xFF | 0x0F = 0xFF (same as v1)
    vor.vv  v4, v1, v2          # v4 = {0xFF, 0xFF, 0xFF, 0xFF}

    # vxor: 0xFF ^ 0x0F = 0xF0
    vxor.vv v5, v1, v2          # v5 = {0xF0, 0xF0, 0xF0, 0xF0}

    # Immediate form
    vand.vi v6, v1, 7           # v6 = 0xFF & 0x07 = {0x07, 0x07, 0x07, 0x07}

    # Scalar form
    li      t0, 0x55
    vxor.vx v7, v1, t0          # v7 = 0xFF ^ 0x55 = {0xAA, 0xAA, 0xAA, 0xAA}

    # Exit — inspect vregs_q[3-7] in GTKWave
    li      a0, 0
    csrw    dscratch, a0
1:  j       1b
